#!/usr/bin/env python3
"""Embed the rendered UI bitmaps (resources/img/ui_*@2x.png) as byte arrays in DecoratorAssets.inc."""
import os
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.path.join(HERE, "..", "resources", "img")
ASSETS = [("Bg", "ui_bg@2x.png", 1), ("KnobBig", "ui_knob_big@2x.png", 81), ("KnobSmall", "ui_knob_small@2x.png", 81), ("Led", "ui_led@2x.png", 2), ("CapBig", "ui_cap_big@2x.png", 1), ("CapSmall", "ui_cap_small@2x.png", 1)]
out = ["// Generated by scripts/embed_assets.py from scripts/render_ui.py output. Do not edit.", "#pragma once", "namespace decorator_assets {",
       "struct Asset { const unsigned char* data; int size; int wPx; int hPx; int frames; int cols; };"]
for name, fn, frames in ASSETS:
    path = os.path.join(RES, fn); b = open(path, "rb").read(); w, h = Image.open(path).size
    out.append(f"static const unsigned char k{name}Data[{len(b)}] = {{")
    for i in range(0, len(b), 32): out.append("  " + ",".join(str(x) for x in b[i:i + 32]) + ",")
    out.append("};")
    import math
    cols = math.ceil(math.sqrt(frames))
    out.append(f"static const Asset k{name} = {{k{name}Data, {len(b)}, {w}, {h}, {frames}, {cols}}};")
out.append("} // namespace decorator_assets")
open(os.path.join(HERE, "..", "DecoratorAssets.inc"), "w").write("\n".join(out) + "\n")
print("embedded", [a[0] for a in ASSETS])
