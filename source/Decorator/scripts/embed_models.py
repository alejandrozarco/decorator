#!/usr/bin/env python3
"""Rewrite DecoratorModels.inc with each capture as a NUL-terminated char array.

Byte arrays avoid MSVC's 64 KB limit on string literals (error C2026). Input: either .nam files
(in capture order) or the existing DecoratorModels.inc (string-literal or array form).
usage: embed_models.py [model0.nam ... model9.nam]
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); INC = os.path.join(HERE, "..", "DecoratorModels.inc")
if len(sys.argv) > 1:
    models = [json.dumps(json.load(open(p)), separators=(",", ":")) for p in sys.argv[1:]]
else:
    s = open(INC).read()
    if 'R"NAM(' in s:
        models = ["".join(re.findall(r'R"NAM\((.*?)\)NAM"', m, re.S))
                  for m in re.findall(r"static const char kModel\d+\[\] = (.*?);\n", s, re.S)]
    else:
        models = [bytes(int(v) for v in body.replace("\n", "").split(",") if v.strip())[:-1].decode()
                  for body in re.findall(r"static const char kModel\d+\[\d+\] = \{(.*?)\};", s, re.S)]
out = ["// Generated by scripts/embed_models.py: the ten Decorator captures (NAM A2 .nam JSON, NUL-terminated). Do not edit.",
       "#pragma once", "namespace decorator_models {"]
for i, js in enumerate(models):
    json.loads(js)
    b = js.encode() + b"\0"
    out.append(f"static const char kModel{i}[{len(b)}] = {{")
    for k in range(0, len(b), 40): out.append(",".join(str(x) for x in b[k:k + 40]) + ",")
    out.append("};")
out.append(f"static const char* const kModels[{len(models)}] = {{" + ", ".join(f"kModel{i}" for i in range(len(models))) + "};")
out.append("} // namespace decorator_models")
open(INC, "w").write("\n".join(out) + "\n")
print("embedded", len(models), "models,", sum(len(m) for m in models), "bytes")
